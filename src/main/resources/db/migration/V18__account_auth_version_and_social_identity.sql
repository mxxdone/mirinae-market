-- 소셜 전용 계정은 로컬 비밀번호가 없으므로 해시를 NULL로 둘 수 있게 한다.
ALTER TABLE accounts ALTER COLUMN password_hash DROP NOT NULL;

-- 인증 버전은 비밀번호 변경·탈퇴 시 증가해 모든 기기의 기존 토큰을 이후 요청부터 거절한다.
ALTER TABLE accounts ADD COLUMN auth_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE accounts ADD CONSTRAINT accounts_auth_version_check CHECK (auth_version >= 0);

-- 소셜 신원은 제공자와 제공자 사용자 식별자 조합으로 하나의 내부 회원에만 연결한다.
CREATE TABLE social_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    provider VARCHAR(10) NOT NULL CHECK (provider IN ('kakao', 'google')),
    subject VARCHAR(100) NOT NULL,
    connected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT social_identities_provider_subject_key UNIQUE (provider, subject)
);
CREATE INDEX social_identities_account_idx ON social_identities(account_id);
