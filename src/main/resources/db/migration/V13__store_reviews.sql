CREATE TABLE store_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_order_id BIGINT NOT NULL UNIQUE REFERENCES store_orders(id),
    store_id BIGINT NOT NULL REFERENCES stores(id),
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    content TEXT NOT NULL CHECK (char_length(content) BETWEEN 1 AND 1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    author_deleted_at TIMESTAMP WITH TIME ZONE,
    admin_deleted_at TIMESTAMP WITH TIME ZONE,
    admin_deleted_by BIGINT REFERENCES accounts(id),
    admin_reason TEXT,
    is_deleted BOOLEAN GENERATED ALWAYS AS
        (author_deleted_at IS NOT NULL OR admin_deleted_at IS NOT NULL) STORED,
    reply_content TEXT CHECK (char_length(reply_content) BETWEEN 1 AND 1000),
    reply_updated_at TIMESTAMP WITH TIME ZONE,
    CHECK ((admin_deleted_at IS NULL AND admin_deleted_by IS NULL AND admin_reason IS NULL)
        OR (admin_deleted_at IS NOT NULL AND admin_deleted_by IS NOT NULL AND admin_reason IS NOT NULL AND char_length(admin_reason) BETWEEN 1 AND 500)),
    CHECK ((reply_content IS NULL) = (reply_updated_at IS NULL))
);
CREATE INDEX store_reviews_public_idx ON store_reviews(store_id,id DESC) WHERE NOT is_deleted;

CREATE TABLE review_deletion_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES store_reviews(id),
    requested_by BIGINT NOT NULL REFERENCES accounts(id),
    reason TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 500),
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at TIMESTAMP WITH TIME ZONE,
    decided_by BIGINT REFERENCES accounts(id),
    decision_reason TEXT,
    CHECK ((status='PENDING' AND decided_at IS NULL AND decided_by IS NULL AND decision_reason IS NULL)
        OR (status<>'PENDING' AND decided_at IS NOT NULL AND decided_by IS NOT NULL AND decision_reason IS NOT NULL AND char_length(decision_reason) BETWEEN 1 AND 500))
);
CREATE UNIQUE INDEX review_deletion_requests_pending_idx ON review_deletion_requests(review_id) WHERE status='PENDING';
