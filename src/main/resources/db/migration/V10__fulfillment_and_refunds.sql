ALTER TABLE order_items ADD COLUMN cancelled_by BIGINT REFERENCES accounts(id);
ALTER TABLE order_items ADD CONSTRAINT cancellation_complete CHECK (
 (cancelled_at IS NULL AND cancellation_type IS NULL AND cancellation_reason IS NULL AND cancelled_by IS NULL)
 OR (cancelled_at IS NOT NULL AND cancellation_type IS NOT NULL AND cancellation_reason IS NOT NULL AND cancelled_by IS NOT NULL));
CREATE TABLE order_operations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES accounts(id), request_key VARCHAR(100) NOT NULL,
 store_order_id BIGINT NOT NULL REFERENCES store_orders(id), fingerprint TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(actor_id,request_key)
);
CREATE TABLE refunds (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operation_id BIGINT NOT NULL UNIQUE REFERENCES order_operations(id),
 store_order_id BIGINT NOT NULL REFERENCES store_orders(id),
 amount_won BIGINT NOT NULL CHECK(amount_won>0),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','COMPLETED','NEEDS_ATTENTION')),
 mode VARCHAR(30) NOT NULL CHECK(mode IN ('SUCCESS','TRANSIENT_FAILURE','PERMANENT_FAILURE','LOST_RESPONSE')),
 attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts>=0),
 last_error VARCHAR(500), due_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, completed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX refunds_due_idx ON refunds(due_at,id) WHERE status='PENDING';
CREATE TABLE mock_refund_results (
 refund_id BIGINT PRIMARY KEY REFERENCES refunds(id),
 amount_won BIGINT NOT NULL CHECK(amount_won>0), completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX store_orders_store_date_idx ON store_orders(store_id,pickup_date,id);
