ALTER TABLE daily_offers ADD COLUMN inventory_version BIGINT NOT NULL DEFAULT 0 CHECK (inventory_version >= 0);
ALTER TABLE pickup_windows ADD COLUMN orders_locked BOOLEAN NOT NULL DEFAULT false;
CREATE TABLE carts (
 buyer_id BIGINT PRIMARY KEY REFERENCES accounts(id),
 version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE TABLE cart_items (
 buyer_id BIGINT NOT NULL REFERENCES carts(buyer_id),
 offer_id BIGINT NOT NULL REFERENCES daily_offers(id),
 quantity INTEGER NOT NULL CHECK (quantity > 0),
 expected_price INTEGER NOT NULL CHECK (expected_price > 0),
 start_time TIME NOT NULL, end_time TIME NOT NULL, order_deadline TIME NOT NULL,
 PRIMARY KEY(buyer_id,offer_id)
);
CREATE TABLE checkouts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 buyer_id BIGINT NOT NULL REFERENCES accounts(id),
 request_key VARCHAR(100) NOT NULL,
 cart_version BIGINT NOT NULL,
 mode VARCHAR(20) NOT NULL CHECK(mode IN ('SUCCESS','FAIL','DELAY','LOST_RESPONSE')),
 status VARCHAR(12) NOT NULL CHECK(status IN ('PENDING','CONFIRMED','FAILED')),
 attempts BIGINT NOT NULL DEFAULT 0 CHECK(attempts>=0),
 error_code VARCHAR(50), message VARCHAR(500),
 total_won BIGINT NOT NULL DEFAULT 0 CHECK(total_won>=0),
 due_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 confirmed_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(buyer_id,request_key), UNIQUE(buyer_id,cart_version)
);
CREATE TABLE checkout_items (
 checkout_id BIGINT NOT NULL REFERENCES checkouts(id),
 offer_id BIGINT NOT NULL REFERENCES daily_offers(id),
 quantity INTEGER NOT NULL CHECK(quantity>0),
 expected_price INTEGER NOT NULL CHECK(expected_price>0),
 start_time TIME NOT NULL,end_time TIME NOT NULL,order_deadline TIME NOT NULL,
 PRIMARY KEY(checkout_id,offer_id)
);
CREATE TABLE store_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 checkout_id BIGINT NOT NULL REFERENCES checkouts(id),
 store_id BIGINT NOT NULL REFERENCES stores(id),
 market_id BIGINT NOT NULL REFERENCES markets(id),
 store_name VARCHAR(100) NOT NULL,pickup_date DATE NOT NULL,
 start_time TIME NOT NULL,end_time TIME NOT NULL,order_deadline TIME NOT NULL,
 UNIQUE(checkout_id,store_id)
);
CREATE TABLE order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_order_id BIGINT NOT NULL REFERENCES store_orders(id),
 offer_id BIGINT NOT NULL REFERENCES daily_offers(id),
 product_name VARCHAR(100) NOT NULL,unit_type VARCHAR(6) NOT NULL,
 unit_amount INTEGER NOT NULL CHECK(unit_amount>0),
 price_won INTEGER NOT NULL CHECK(price_won>0),quantity INTEGER NOT NULL CHECK(quantity>0),
 UNIQUE(store_order_id,offer_id)
);
CREATE INDEX checkouts_buyer_idx ON checkouts(buyer_id,id);
CREATE INDEX checkouts_pending_idx ON checkouts(due_at,id) WHERE status='PENDING';
