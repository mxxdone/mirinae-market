ALTER TABLE stores ADD COLUMN operation_updated_at TIMESTAMP WITH TIME ZONE;
CREATE TABLE store_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id BIGINT NOT NULL REFERENCES stores(id), buyer_id BIGINT NOT NULL REFERENCES accounts(id),
 type VARCHAR(30) NOT NULL CHECK(type IN ('CLOSURE_SUSPECTED','INACTIVE','LOCATION_ERROR')),
 description VARCHAR(500) NOT NULL CHECK(length(trim(description)) BETWEEN 1 AND 500),
 status VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','REVIEWING','RESOLVED')),
 resolution VARCHAR(500), updated_by BIGINT REFERENCES accounts(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK(status<>'RESOLVED' OR (resolution IS NOT NULL AND length(trim(resolution)) BETWEEN 1 AND 500))
);
CREATE UNIQUE INDEX store_reports_open_idx ON store_reports(buyer_id,store_id,type) WHERE status<>'RESOLVED';
CREATE INDEX store_reports_status_idx ON store_reports(status,id);
