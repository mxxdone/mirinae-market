CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES stores(id),
    name VARCHAR(100) NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
    description VARCHAR(1000) NOT NULL DEFAULT '',
    unit_type VARCHAR(6) NOT NULL CHECK (unit_type IN ('WEIGHT', 'COUNT')),
    unit_amount INTEGER NOT NULL CHECK (unit_amount > 0),
    CHECK (unit_type <> 'WEIGHT' OR unit_amount % 100 = 0),
    UNIQUE (id, store_id)
);
CREATE INDEX products_store_id_idx ON products(store_id, id);
CREATE TABLE pickup_windows (
    store_id BIGINT NOT NULL REFERENCES stores(id),
    pickup_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    PRIMARY KEY (store_id, pickup_date),
    CHECK (start_time < end_time),
    CHECK (extract(second FROM start_time) = 0 AND extract(second FROM end_time) = 0)
);
CREATE TABLE daily_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    pickup_date DATE NOT NULL,
    price_won INTEGER NOT NULL CHECK (price_won > 0),
    online_quantity INTEGER NOT NULL CHECK (online_quantity >= 0),
    UNIQUE (product_id, pickup_date),
    FOREIGN KEY (product_id, store_id) REFERENCES products(id, store_id),
    FOREIGN KEY (store_id, pickup_date) REFERENCES pickup_windows(store_id, pickup_date)
);
CREATE INDEX daily_offers_date_store_idx ON daily_offers(pickup_date, store_id, id);